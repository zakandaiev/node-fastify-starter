import { createContext, getContext } from '#core/context/index.js';
import { handleError, handleNotFound } from '#core/error/handler.js';
import { buildTestApp, readRequestId } from '#root/tests/helper/app.js';
import { createLogSink } from '#root/tests/helper/log.js';
import { sendRawRequest } from '#root/tests/helper/socket.js';
import assert from 'node:assert/strict';
import http from 'node:http';
import { Writable } from 'node:stream';
import { describe, test } from 'node:test';
import { setTimeout as sleep } from 'node:timers/promises';

const LOOPBACK = '127.0.0.1';
const CLIENT_REQUEST_ID = '019a0000-0000-7000-8000-000000000000';
const REQUEST_COUNT = 20;
const SLOW_MS = 20;
const FAST_MS = 1;
const BODY_DELAY_MS = 20;
const RESPONSE_TIMEOUT_MS = 3000;
const PLUGIN_NAMES = ['context', 'response', 'error-handler'];
const REQUEST_KEYS = ['log', 'requestId'];

const REQUEST_CONTEXT = Object.freeze({
  isFrozen: true,
  isRequestId: true,
  isRequestLog: true,
  isAppConfig: true,
});

function inspectContext(request) {
  const context = getContext();

  return {
    isFrozen: Object.isFrozen(context),
    isRequestId: context.requestId === request.id,
    isRequestLog: context.log === request.log,
    isAppConfig: context.config === request.server.config,
  };
}

async function useShop(fastify, { seen }) {
  fastify.setNotFoundHandler((request, reply) => {
    seen.notFoundHandler = inspectContext(request);
    handleNotFound(request, reply);
  });
  fastify.get('/items', (request) => inspectContext(request));
}

function hasContext() {
  try {
    getContext();

    return true;
  } catch {
    return false;
  }
}

function flushEvents() {
  return new Promise((resolve) => { setImmediate(resolve); });
}

// The body leaves in a later packet than the headers: its parser then runs from the socket,
// outside the async chain of the hook that entered the context.
function postInTwoPackets(port, path, body) {
  return new Promise((resolve, reject) => {
    const request = http.request({
      host: LOOPBACK,
      port,
      path,
      method: 'POST',
      agent: false,
      headers: {
        connection: 'close',
        'content-type': 'application/json',
        'content-length': Buffer.byteLength(body),
      },
    }, (response) => {
      const chunks = [];

      response.on('data', (chunk) => chunks.push(chunk));
      response.once('end', () => resolve({
        statusCode: response.statusCode,
        headers: response.headers,
        payload: Buffer.concat(chunks).toString(),
      }));
    });

    request.setTimeout(RESPONSE_TIMEOUT_MS, () => request.destroy(new Error('The server did not answer')));
    request.once('error', reject);
    request.flushHeaders();
    setTimeout(() => request.end(body), BODY_DELAY_MS);
  });
}

describe('plugins', () => {
  test('are registered under the names context, response and error-handler', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    assert.deepEqual(PLUGIN_NAMES.map((name) => fastify.hasPlugin(name)), [true, true, true]);
  });
});

describe('context plugin: X-Request-Id', () => {
  test('answers with the id of the request, a UUIDv7 generated by the server', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', (request) => ({ id: request.id }));

    const response = await fastify.inject('/items');

    assert.equal(response.statusCode, 200);
    assert.equal(response.json().id, readRequestId(response));
  });

  test('gives every request an id of its own', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', () => ({}));

    const responses = await Promise.all(Array.from({ length: REQUEST_COUNT }, () => fastify.inject('/items')));
    const requestIds = responses.map((response) => readRequestId(response));

    assert.equal(new Set(requestIds).size, REQUEST_COUNT);
  });

  test('ignores an id sent by the client', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', (request) => ({ id: request.id }));

    const responses = await Promise.all(['client-chosen-id', CLIENT_REQUEST_ID].map((clientId) => fastify.inject({
      url: '/items',
      headers: { 'x-request-id': clientId, 'request-id': clientId },
    })));

    responses.forEach((response) => {
      const requestId = readRequestId(response);

      assert.notEqual(requestId, CLIENT_REQUEST_ID);
      assert.equal(response.json().id, requestId);
    });
  });

  test('is on a 404 for an unknown URL, the same id as in the body', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const response = await fastify.inject('/missing');

    assert.equal(response.statusCode, 404);
    assert.equal(response.json().meta.requestId, readRequestId(response));
  });

  test('is on a 500 for an error thrown by a handler', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', async () => {
      throw new Error('boom');
    });

    const response = await fastify.inject('/items');

    assert.equal(response.statusCode, 500);
    assert.equal(response.json().meta.requestId, readRequestId(response));
  });

  test('is on a 422 for a request that fails validation', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', {
      schema: {
        querystring: {
          type: 'object',
          properties: {
            limit: { type: 'integer' },
          },
        },
      },
    }, () => ({}));

    const response = await fastify.inject('/items?limit=ten');

    assert.equal(response.statusCode, 422);
    assert.equal(response.json().meta.requestId, readRequestId(response));
  });

  test('is on a 204, which has no body to carry the id', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.delete('/items/1', (request, reply) => reply.code(204).send());

    const response = await fastify.inject({ method: 'DELETE', url: '/items/1' });

    assert.equal(response.statusCode, 204);
    assert.equal(response.payload, '');
    readRequestId(response);
  });
});

describe('context plugin: getContext()', () => {
  test('returns the frozen context of the request inside a handler, also after an await', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', async (request) => {
      const before = inspectContext(request);

      await sleep(FAST_MS);

      return { before, after: inspectContext(request) };
    });

    const response = await fastify.inject('/items');

    assert.equal(response.statusCode, 200);
    assert.deepEqual(response.json(), { before: REQUEST_CONTEXT, after: REQUEST_CONTEXT });
  });

  test('carries the id that goes into the X-Request-Id header', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', () => ({ requestId: getContext().requestId }));

    const response = await fastify.inject('/items');

    assert.equal(response.json().requestId, readRequestId(response));
  });

  test('differs from the context of the app only in the log and the id of the request', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    let context = null;

    fastify.get('/items', () => {
      context = getContext();

      return {};
    });

    await fastify.inject('/items');

    const sharedKeys = Object.keys(fastify.context).filter((key) => !REQUEST_KEYS.includes(key));

    assert.notEqual(context, fastify.context);
    assert.equal(context.config, fastify.config);
    assert.deepEqual(Object.keys(context), Object.keys(fastify.context));
    sharedKeys.forEach((key) => assert.equal(context[key], fastify.context[key], key));
    assert.notEqual(context.log, fastify.log);
    assert.equal(fastify.context.log, fastify.log);
    assert.equal(fastify.context.requestId, null);
  });

  test('carries the services that the context of the app holds when the request comes', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const services = { db: {}, redis: {}, cacheRedis: {} };
    let context = null;

    fastify.context = createContext({ ...fastify.context, ...services });
    fastify.get('/items', () => {
      context = getContext();

      return {};
    });

    await fastify.inject('/items');

    assert.equal(context.db, services.db);
    assert.equal(context.redis, services.redis);
    assert.equal(context.cacheRedis, services.cacheRedis);
    assert.equal(context.config, fastify.config);
  });

  test('is there in every hook of the lifecycle, a later onRequest hook included', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const seen = {};

    ['onRequest', 'preParsing', 'preValidation', 'preHandler', 'onResponse'].forEach((name) => {
      fastify.addHook(name, async (request) => {
        seen[name] = inspectContext(request);
      });
    });
    ['preSerialization', 'onSend'].forEach((name) => {
      fastify.addHook(name, async (request, reply, payload) => {
        seen[name] = inspectContext(request);

        return payload;
      });
    });
    fastify.get('/items', () => ({}));

    const response = await fastify.inject('/items');

    await flushEvents();

    assert.equal(response.statusCode, 200);
    assert.deepEqual(seen, {
      onRequest: REQUEST_CONTEXT,
      preParsing: REQUEST_CONTEXT,
      preValidation: REQUEST_CONTEXT,
      preHandler: REQUEST_CONTEXT,
      preSerialization: REQUEST_CONTEXT,
      onSend: REQUEST_CONTEXT,
      onResponse: REQUEST_CONTEXT,
    });
  });

  test('is there in a callback hook as well as in an async one', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const seen = {};

    fastify.addHook('onRequest', (request, reply, done) => {
      seen.onRequest = inspectContext(request);
      done();
    });
    fastify.addHook('preHandler', (request, reply, done) => {
      seen.preHandler = inspectContext(request);
      done();
    });
    fastify.addHook('onSend', (request, reply, payload, done) => {
      seen.onSend = inspectContext(request);
      done(null, payload);
    });
    fastify.get('/items', (request) => {
      seen.handler = inspectContext(request);

      return {};
    });

    const response = await fastify.inject('/items');

    assert.equal(response.statusCode, 200);
    assert.deepEqual(seen, {
      onRequest: REQUEST_CONTEXT,
      preHandler: REQUEST_CONTEXT,
      handler: REQUEST_CONTEXT,
      onSend: REQUEST_CONTEXT,
    });
  });

  test('is one object from the first hook of a request to the last', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const contexts = [];

    fastify.addHook('onRequest', async () => {
      contexts.push(getContext());
    });
    fastify.addHook('onSend', async (request, reply, payload) => {
      contexts.push(getContext());

      return payload;
    });
    fastify.get('/items', async () => {
      contexts.push(getContext());
      await sleep(FAST_MS);
      contexts.push(getContext());

      return {};
    });

    await fastify.inject('/items');

    assert.equal(contexts.length, 4);
    assert.equal(new Set(contexts).size, 1);
  });

  test('is there on the error path: in an onError hook and in the error handler of a route', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const seen = {};

    fastify.addHook('onError', async (request) => {
      seen.onError = inspectContext(request);
    });
    fastify.get('/items', {
      errorHandler(error, request, reply) {
        seen.errorHandler = inspectContext(request);
        handleError(error, request, reply);
      },
    }, async () => {
      throw new Error('boom');
    });

    const response = await fastify.inject('/items');

    assert.equal(response.statusCode, 500);
    assert.deepEqual(seen, { onError: REQUEST_CONTEXT, errorHandler: REQUEST_CONTEXT });
  });

  test('is there when the request fails validation', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const seen = {};

    fastify.addHook('onError', async (request) => {
      seen.onError = inspectContext(request);
    });
    fastify.addHook('onSend', async (request, reply, payload) => {
      seen.onSend = inspectContext(request);

      return payload;
    });
    fastify.post('/items', {
      schema: {
        body: {
          type: 'object',
          required: ['name'],
          properties: {
            name: { type: 'string' },
          },
        },
      },
    }, () => ({}));

    const response = await fastify.inject({ method: 'POST', url: '/items', payload: {} });

    assert.equal(response.statusCode, 422);
    assert.deepEqual(seen, { onError: REQUEST_CONTEXT, onSend: REQUEST_CONTEXT });
  });

  test('is there for an unknown URL', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const seen = {};

    fastify.addHook('onRequest', async (request) => {
      seen.onRequest = inspectContext(request);
    });
    fastify.addHook('preHandler', async (request) => {
      seen.preHandler = inspectContext(request);
    });
    fastify.addHook('onSend', async (request, reply, payload) => {
      seen.onSend = inspectContext(request);

      return payload;
    });

    const response = await fastify.inject('/missing');

    assert.equal(response.statusCode, 404);
    assert.deepEqual(seen, { onRequest: REQUEST_CONTEXT, preHandler: REQUEST_CONTEXT, onSend: REQUEST_CONTEXT });
  });

  test('is there in a not-found handler', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    const seen = {};

    await fastify.register(useShop, { prefix: '/shop', seen });

    const response = await fastify.inject('/shop/missing');

    assert.equal(response.statusCode, 404);
    assert.equal(response.json().meta.requestId, readRequestId(response));
    assert.deepEqual(seen, { notFoundHandler: REQUEST_CONTEXT });
  });

  test('covers the routes of an encapsulated plugin', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    await fastify.register(useShop, { prefix: '/shop', seen: {} });

    const response = await fastify.inject('/shop/items');

    assert.equal(response.statusCode, 200);
    assert.deepEqual(response.json(), REQUEST_CONTEXT);
    readRequestId(response);
  });

  test('survives the parsing of a JSON body', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.post('/items', (request) => ({ ...inspectContext(request), name: request.body.name }));

    const response = await fastify.inject({ method: 'POST', url: '/items', payload: { name: 'Anna' } });

    assert.equal(response.statusCode, 200);
    assert.deepEqual(response.json(), { ...REQUEST_CONTEXT, name: 'Anna' });
  });

  test('survives a body that arrives after the headers over a real connection', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.post('/items', (request) => ({ ...inspectContext(request), name: request.body.name }));

    await fastify.listen({ host: LOOPBACK, port: 0 });

    const response = await postInTwoPackets(fastify.server.address().port, '/items', JSON.stringify({ name: 'Anna' }));

    assert.equal(response.statusCode, 200);
    assert.deepEqual(JSON.parse(response.payload), { ...REQUEST_CONTEXT, name: 'Anna' });
    readRequestId(response);
  });

  test('keeps two concurrent requests apart', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items/:speed', async (request) => {
      await sleep(request.params.speed === 'slow' ? SLOW_MS : FAST_MS);

      return { requestId: getContext().requestId };
    });

    const [slow, fast] = await Promise.all([fastify.inject('/items/slow'), fastify.inject('/items/fast')]);

    assert.equal(slow.json().requestId, readRequestId(slow));
    assert.equal(fast.json().requestId, readRequestId(fast));
    assert.notEqual(slow.json().requestId, fast.json().requestId);
  });

  test('keeps the requests of one keep-alive connection apart', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    fastify.get('/items', async (request) => {
      await sleep(FAST_MS);

      return { contextId: getContext().requestId, id: request.id };
    });

    await fastify.listen({ host: LOOPBACK, port: 0 });

    const text = await sendRawRequest(fastify.server.address().port, [
      'GET /items HTTP/1.1\r\nHost: localhost\r\n\r\n',
      'GET /items HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n',
    ].join(''));
    const headerIds = [...text.matchAll(/x-request-id: ([0-9a-f-]+)\r\n/gi)].map((match) => match[1]);
    const bodies = [...text.matchAll(/\{"contextId":[^}]+\}/g)].map((match) => JSON.parse(match[0]));

    assert.equal(headerIds.length, 2);
    assert.notEqual(headerIds[0], headerIds[1]);
    assert.deepEqual(bodies, headerIds.map((id) => ({ contextId: id, id })));
  });

  test('throws outside a request: before it, after it and at startup', async (t) => {
    const fastify = await buildTestApp();
    t.after(() => fastify.close());

    let isContextAtStartup = null;

    fastify.addHook('onReady', async () => {
      isContextAtStartup = hasContext();
    });
    fastify.get('/items', () => ({ isContext: hasContext() }));

    assert.throws(() => getContext(), /No active context/);

    const response = await fastify.inject('/items');

    assert.deepEqual(response.json(), { isContext: true });
    assert.equal(isContextAtStartup, false);
    assert.throws(() => getContext(), /No active context/);
  });

  test('is there when the error handler of the app logs, but not on the frameworkErrors path, where no hook runs', async (t) => {
    const lines = [];
    const stream = new Writable({
      write(chunk, encoding, callback) {
        lines.push({ ...JSON.parse(chunk.toString()), isContext: hasContext() });
        callback();
      },
    });
    const fastify = await buildTestApp({ logger: { level: 'warn', stream } });
    t.after(() => fastify.close());

    function readContextFlags(response) {
      const requestId = readRequestId(response);
      const flags = lines
        .filter((line) => line.requestId === requestId)
        .map((line) => line.isContext);

      return [...new Set(flags)];
    }

    fastify.get('/items', async () => {
      throw new Error('boom');
    });

    const [badUrl, thrown] = await Promise.all([fastify.inject('/%FF'), fastify.inject('/items')]);

    assert.equal(badUrl.statusCode, 400);
    assert.equal(thrown.statusCode, 500);
    assert.deepEqual(readContextFlags(badUrl), [false]);
    assert.deepEqual(readContextFlags(thrown), [true]);
  });
});

describe('context plugin: logging', () => {
  test('a line written through getContext().log carries the requestId of the request', async (t) => {
    const sink = createLogSink();
    const fastify = await buildTestApp({ logger: { level: 'info', stream: sink.stream } });
    t.after(() => fastify.close());

    fastify.get('/items', () => {
      getContext().log.info({ itemsCount: 3 }, 'Items listed');

      return {};
    });

    const response = await fastify.inject('/items');
    const line = sink.lines.find((entry) => entry.msg === 'Items listed');

    assert.equal(line.requestId, readRequestId(response));
    assert.equal(line.itemsCount, 3);
    assert.equal(Object.hasOwn(line, 'reqId'), false);
  });

  test('two requests in flight log under their own ids', async (t) => {
    const sink = createLogSink();
    const fastify = await buildTestApp({ logger: { level: 'info', stream: sink.stream } });
    t.after(() => fastify.close());

    fastify.get('/items/:speed', async (request) => {
      await sleep(request.params.speed === 'slow' ? SLOW_MS : FAST_MS);
      getContext().log.info({ speed: request.params.speed }, 'Items listed');

      return {};
    });

    const [slow, fast] = await Promise.all([fastify.inject('/items/slow'), fastify.inject('/items/fast')]);
    const requestIds = Object.fromEntries(
      sink.lines
        .filter((line) => line.msg === 'Items listed')
        .map((line) => [line.speed, line.requestId]),
    );

    assert.deepEqual(requestIds, { slow: readRequestId(slow), fast: readRequestId(fast) });
  });
});
